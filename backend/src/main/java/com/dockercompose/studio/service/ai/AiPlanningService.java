package com.dockercompose.studio.service.ai;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import lombok.extern.slf4j.Slf4j;
import org.springframework.stereotype.Service;

import java.util.*;

@Service
@Slf4j
public class AiPlanningService {

    private final ObjectMapper objectMapper = new ObjectMapper();

    public String systemPrompt() {
        return """
                You are a Docker Compose topology planner for local development.
                Respond ONLY with valid JSON matching this schema:
                {
                  "serviceIds": ["catalog-id", ...],
                  "dependencies": [{"from": "catalog-id", "to": "catalog-id"}],
                  "explanation": "short explanation"
                }
                Rules:
                - Use ONLY catalog IDs from the allowed list.
                - Include dependencies from app services to databases/cache when relevant.
                - For Kafka, include zookeeper and an edge kafka -> zookeeper.
                - Keep serviceIds unique and practical for the user request.
                """;
    }

    public String userPrompt(String prompt, List<String> catalogIds) {
        return "Allowed catalog IDs: " + String.join(", ", catalogIds)
                + "\n\nUser request:\n" + prompt;
    }

    public Optional<AiPlan> parsePlan(String content, String providerId) {
        if (content == null || content.isBlank()) return Optional.empty();

        try {
            String trimmed = content.trim();
            if (trimmed.startsWith("```")) {
                trimmed = trimmed.replaceFirst("^```(?:json)?\\s*", "").replaceFirst("\\s*```$", "");
            }

            JsonNode root = objectMapper.readTree(trimmed);
            Set<String> serviceIds = new LinkedHashSet<>();
            if (root.has("serviceIds") && root.get("serviceIds").isArray()) {
                for (JsonNode id : root.get("serviceIds")) {
                    if (id.isTextual()) serviceIds.add(id.asText());
                }
            }

            List<AiPlan.AiDependency> dependencies = new ArrayList<>();
            if (root.has("dependencies") && root.get("dependencies").isArray()) {
                for (JsonNode dep : root.get("dependencies")) {
                    if (dep.has("from") && dep.has("to")) {
                        dependencies.add(new AiPlan.AiDependency(dep.get("from").asText(), dep.get("to").asText()));
                    }
                }
            }

            String explanation = root.has("explanation")
                    ? root.get("explanation").asText()
                    : "Generated by " + providerId;

            if (serviceIds.isEmpty()) return Optional.empty();
            return Optional.of(new AiPlan(serviceIds, dependencies, explanation, providerId));
        } catch (Exception e) {
            log.warn("{} plan parse failed: {}", providerId, e.getMessage());
            return Optional.empty();
        }
    }
}
