import JSZip from 'jszip';

export async function exportYaml(content: string, filename = 'docker-compose.yml') {
  const blob = new Blob([content], { type: 'text/yaml' });
  downloadBlob(blob, filename);
}

export async function exportZip(composeYaml: string, projectName: string) {
  const zip = new JSZip();
  zip.file('docker-compose.yml', composeYaml);
  zip.file(
    'README.md',
    `# ${projectName}\n\nGenerated by [Docker Compose Studio](https://github.com/MMCISAGOODMAN/docker-compose-studio)\n\n## Quick Start\n\n\`\`\`bash\ndocker compose up -d\n\`\`\`\n`
  );
  zip.file('.env.example', '# Copy to .env and customize\nCOMPOSE_PROJECT_NAME=dcs-environment\n');

  const blob = await zip.generateAsync({ type: 'blob' });
  downloadBlob(blob, `${projectName.replace(/\s+/g, '-').toLowerCase()}.zip`);
}

function downloadBlob(blob: Blob, filename: string) {
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  a.click();
  URL.revokeObjectURL(url);
}

export function saveAs(blob: Blob, filename: string) {
  downloadBlob(blob, filename);
}
